let with_directory ~f =
  Filesystem_async.with_temp_dir ~in_dir:(File_path.of_string ".") (fun dir ->
    f (File_path.Absolute.to_string dir))
;;

let save_config dir sections =
  Writer.save
    (dir ^/ "gk-tools.sexp")
    ~contents:(Sexp.to_string [%sexp (sections : (string * Sexp.t) list)])
;;

let run_gkt ~dir ~env ~stdin args =
  let%bind process =
    Process.create_exn
      ~env:(`Extend (("XDG_CONFIG_HOME", dir) :: env))
      ~stdin
      ~prog:"setsid"
      ~args:("../bin/main.exe" :: args)
      ()
  in
  let output = Process.collect_output_and_wait process in
  match%bind Clock_ns.with_timeout (Time_ns.Span.of_int_sec 10) output with
  | `Result output -> return output
  | `Timeout ->
    Process.send_signal process Signal.kill;
    let%map output in
    raise_s [%message "test command timed out" (output : Process.Output.t)]
;;

let success_exn (output : Process.Output.t) =
  match output.exit_status with
  | Ok () -> output.stdout
  | Error _ -> raise_s [%message "test command failed" (output : Process.Output.t)]
;;

let log_time = lazy (Re.Perl.compile_pat {|\(time \([^)]*\)\)|})

let print_logs ~tmp_dir (output : Process.Output.t) =
  String.substr_replace_all output.stderr ~pattern:tmp_dir ~with_:"$TMPDIR"
  |> Re.replace_string (force log_time) ~by:"(time (<time>))"
  |> print_string
;;

module Answer = struct
  type t =
    | Folder of string
    | No_match
    | Malformed of string
    | Incomplete
    | Refused
  [@@deriving sexp_of]
end

let response_json answer =
  let decision folder =
    `Object [ "target_folder", folder; "reason", `String "Test model classification." ]
    |> Jsonaf.to_string
  in
  let status =
    match answer with
    | Answer.Incomplete -> "incomplete"
    | _ -> "completed"
  in
  let content =
    match answer with
    | Folder text ->
      [ `Object
          [ "type", `String "output_text"
          ; "text", `String (decision (`String text))
          ; "annotations", `Array []
          ]
      ]
    | No_match ->
      [ `Object [ "type", `String "output_text"; "text", `String (decision `Null) ] ]
    | Malformed text ->
      [ `Object [ "type", `String "output_text"; "text", `String text ] ]
    | Incomplete ->
      [ `Object
          [ "type", `String "output_text"
          ; "text", `String (decision (`String "Receipts"))
          ]
      ]
    | Refused ->
      [ `Object
          [ "type", `String "output_text"
          ; "text", `String (decision (`String "Receipts"))
          ]
      ; `Object [ "type", `String "refusal"; "refusal", `String "No" ]
      ]
  in
  `Object
    [ "id", `String "resp_test"
    ; "object", `String "response"
    ; "status", `String status
    ; ( "output"
      , `Array
          [ `Object
              [ "id", `String "msg_test"
              ; "type", `String "message"
              ; "role", `String "assistant"
              ; "status", `String "completed"
              ; "content", `Array content
              ]
          ] )
    ]
  |> Jsonaf.to_string
;;

let classify_mail () =
  with_directory ~f:(fun dir ->
    let mail = dir ^/ "mail" in
    let source = mail ^/ "INBOX/cur/one,U=17:2,S" in
    let destination = mail ^/ "Receipts/cur/one:2,S" in
    let calls = mail ^/ "notmuch-calls" in
    let email =
      "Subject: invoice\n\
       Message-ID: (sender <decoy@example.com> (nested) escaped \\))\n\
       \t<invoice@example.com> (generated by sender)\n\n\
       Invoice attached.\n"
    in
    let%bind () =
      Deferred.List.iter [ "INBOX"; "Receipts" ] ~how:`Sequential ~f:(fun folder ->
        Deferred.List.iter [ "cur"; "new"; "tmp" ] ~how:`Sequential ~f:(fun subdir ->
          Unix.mkdir ~p:() (mail ^/ folder ^/ subdir)))
    in
    let%bind () = Unix.mkdir (dir ^/ "bin") in
    let%bind () = Writer.save source ~contents:email
    and () =
      Writer.save
        ~perm:0o700
        (dir ^/ "bin/notmuch")
        ~contents:
          {|#!/usr/bin/env bash
printf '%s\n' "$1" >> "$MAIL_ROOT/notmuch-calls"
case "$1" in
  search)
    printf '%s\n' "$4" >> "$MAIL_ROOT/notmuch-queries"
    case "$4" in
      'id:"invoice@example.com"') printf '%s\n' "$MAIL_ROOT/INBOX/cur/one,U=17:2,S" ;;
      *) : ;;
    esac
    ;;
  *) exit 1 ;;
esac
|}
    in
    let env =
      [ "PATH", [%string "%{dir ^/ \"bin\"}:%{Sys.getenv_exn \"PATH\"}"]
      ; "MAIL_ROOT", mail
      ; "LLM_GATEWAY_TOKEN", "test-secret"
      ; "TOKEN_CALLS", dir ^/ "token-calls"
      ]
    in
    let args = [ "misc"; "classify-mail"; "-folder"; "INBOX"; "-file"; source ] in
    let answer = ref (Answer.Folder "Receipts") in
    let actual_auth = ref None in
    let received = ref [] in
    let handler ~body _ request =
      actual_auth := Cohttp.Header.get (Cohttp.Request.headers request) "authorization";
      let%bind body = Cohttp_async.Body.to_string body in
      let json = Jsonaf.of_string body in
      let message = Jsonaf.member_exn "input" json |> Jsonaf.list_exn |> List.hd_exn in
      let content = Jsonaf.member_exn "content" message |> Jsonaf.string_exn in
      if List.is_empty !received
      then
        Jsonaf.member_exn "instructions" json
        |> Jsonaf.string_exn
        |> String.split_lines
        |> List.take _ 3
        |> [%sexp_of: string list]
        |> print_s;
      received := content :: !received;
      let outcome =
        if String.is_substring content ~substring:"Subject: second"
        then Answer.No_match
        else !answer
      in
      Cohttp_async.Server.respond_string (response_json outcome)
    in
    Test_server.with_server handler ~f:(fun port ->
      let settings =
        Gk_tools.Config.Llm_completions_settings.t_of_sexp
          (Sexp.of_string
             [%string
               {|((url http://127.0.0.1:%{port#Int}/v1/responses)
                  (token (env LLM_GATEWAY_TOKEN)) (model mail-model)
                   (system_prompt "Shared LLM context")
                   (reasoning_effort low) (timeout 5s))|}])
      in
      let destinations : Gk_tools.Config.Classify_mail_settings.t =
        { destinations =
            [ { folder = File_path.Relative.of_string "Receipts"
              ; description = "Invoices"
              }
            ]
        ; system_prompt = Some (String.Utf8.of_string "Classify personal mail.")
        }
      in
      let configure settings =
        save_config
          dir
          [ "llm_completions", Gk_tools.Config.Llm_completions_settings.sexp_of_t settings
          ; "classify_mail", Gk_tools.Config.Classify_mail_settings.sexp_of_t destinations
          ]
      in
      let run stdin args = run_gkt ~dir ~env ~stdin args in
      let%bind () = configure settings in
      let%bind output = run email args in
      ignore (success_exn output : string);
      let%bind moved = Reader.file_contents destination
      and log = Reader.file_contents calls
      and query = Reader.file_contents (mail ^/ "notmuch-queries")
      and source_exists = Sys.file_exists source in
      print_s
        [%message
          ""
            ~mail_preserved:(String.equal moved email : bool)
            ~notmuch_calls:(String.split_lines log : string list)
            ~query:(String.strip query : string)
            ~source_exists:(Poly.equal source_exists `Yes : bool)];
      let%bind () = Unix.rename ~src:destination ~dst:source
      and () = Unix.unlink calls in
      let existing = "existing destination" in
      let%bind () = Writer.save destination ~contents:existing in
      let%bind output = run email (args @ [ "-log-level"; "Error" ]) in
      print_logs ~tmp_dir:dir output;
      let%bind original = Reader.file_contents source
      and retained = Reader.file_contents destination
      and log = Reader.file_contents calls in
      print_s
        [%message
          "destination collision"
            ~source_preserved:(String.equal original email : bool)
            ~destination_preserved:(String.equal retained existing : bool)
            ~notmuch_calls:(String.split_lines log : string list)];
      let%bind () = Unix.unlink destination
      and () = Unix.unlink calls in
      let%bind () =
        Deferred.List.iter
          [ Answer.Folder "Unknown"; Malformed "{}"; Incomplete; Refused ]
          ~how:`Sequential
          ~f:(fun outcome ->
            answer := outcome;
            let%map output = run email (args @ [ "-log-level"; "Error" ]) in
            print_s [%message (outcome : Answer.t)];
            print_logs ~tmp_dir:dir output)
      in
      let%bind calls_exist = Sys.file_exists calls in
      print_s
        [%message
          "after rejected answers" ~notmuch_called:(Poly.equal calls_exist `Yes : bool)];
      answer := No_match;
      let%bind output = run email args in
      ignore (success_exn output : string);
      let%bind calls_exist = Sys.file_exists calls
      and source_exists = Sys.file_exists source in
      print_s
        [%message
          "JSON null"
            ~notmuch_called:(Poly.equal calls_exist `Yes : bool)
            ~source_preserved:(Poly.equal source_exists `Yes : bool)];
      answer := Folder "Receipts";
      let batch =
        [%string
          "From sender@example.com Thu Jan 1 00:00:00 2026\n\
           %{email}From other@example.com Thu Jan 1 00:00:00 2026\n\
           Subject: second\n\
           Message-ID: <second@example.com>\n\n\
           Other mail.\n"]
      in
      let%bind output = run batch (args @ [ "-dry-run"; "-jobs"; "1" ]) in
      ignore (success_exn output : string);
      print_logs ~tmp_dir:dir output;
      let%bind calls_exist = Sys.file_exists calls in
      print_s [%message "dry run" ~notmuch_called:(Poly.equal calls_exist `Yes : bool)];
      answer := No_match;
      let%bind output =
        run
          [%string "%{email}%{String.make 100_000 'x'}"]
          (args @ [ "-dry-run"; "-log-level"; "Error" ])
      in
      print_logs ~tmp_dir:dir output;
      let%bind output = run [%string "%{email}caf\233\n"] (args @ [ "-dry-run" ]) in
      ignore (success_exn output : string);
      print_s
        [%message
          "invalid UTF-8"
            ~normalized:
              (Option.equal
                 String.equal
                 (List.hd !received)
                 (Some [%string "%{email}caf\239\191\189\n"])
               : bool)];
      let%bind () =
        configure
          { settings with
            token = Some (Command "printf x >> \"$TOKEN_CALLS\"; printf 'test-secret\\n'")
          }
      in
      let%bind output = run batch (args @ [ "-dry-run" ]) in
      ignore (success_exn output : string);
      let%map token_calls = Reader.file_contents (dir ^/ "token-calls") in
      print_s
        [%message (token_calls : string) ~authorization:(!actual_auth : string option)]))
;;

let caldav_secret () =
  with_directory ~f:(fun dir ->
    let passwords = ref [] in
    let handler ~body _ request =
      let%bind body = Cohttp_async.Body.to_string body in
      if List.is_empty !passwords
      then
        print_s
          [%message
            ""
              ~method_:(Cohttp.Request.meth request : Cohttp.Code.meth)
              ~path:(Uri.path (Cohttp.Request.uri request) : string)
              ~uid_present:(String.is_substring body ~substring:"UID:test-event" : bool)];
      (match Cohttp.Header.get_authorization (Cohttp.Request.headers request) with
       | Some (`Basic (username, password)) ->
         passwords := (username, password) :: !passwords
       | _ -> raise_s [%message "missing basic authentication"]);
      Cohttp_async.Server.respond_string ~status:`Created ""
    in
    let stdin =
      String.concat
        ~sep:"\r\n"
        [ "BEGIN:VCALENDAR"
        ; "VERSION:2.0"
        ; "PRODID:-//Test//EN"
        ; "BEGIN:VEVENT"
        ; "UID:test-event"
        ; "END:VEVENT"
        ; "END:VCALENDAR"
        ; ""
        ]
    in
    let run args = run_gkt ~dir ~env:[] ~stdin ("caldav-upload" :: args) in
    Test_server.with_server handler ~f:(fun port ->
      let url = [%string "http://127.0.0.1:%{port#Int}/calendar"] in
      let configure source =
        let settings : Gk_tools.Config.Caldav_upload_settings.t =
          { server_url = url; username = Some "user"; password = Some source }
        in
        save_config
          dir
          [ "caldav_upload", Gk_tools.Config.Caldav_upload_settings.sexp_of_t settings ]
      in
      let report args =
        let%map output = run args in
        print_s
          [%message
            ""
              ~success:(Result.is_ok output.exit_status : bool)
              ~credentials:(List.hd !passwords : (string * string) option)]
      in
      let%bind () = configure (Command "printf 'command-secret\\n'") in
      let%bind () = report [] in
      let%bind () = configure (Command "exit 9") in
      let%bind () = report [ "-password"; "cli-secret" ] in
      let%bind () = save_config dir [] in
      let%bind () =
        report [ "-server-url"; url; "-username"; "user"; "-password"; "cli-secret" ]
      in
      let%bind () =
        configure (Command "if read -r value; then exit 9; fi; printf headless-secret")
      in
      report []))
;;

let%expect_test "gateway classification, dry run, and token sources" =
  let%bind () = classify_mail () in
  [%expect
    {|
    ("Shared LLM context" "" "Classify personal mail.")
    ((mail_preserved true) (notmuch_calls (search))
     (query "id:\"invoice@example.com\"") (source_exists false))
    (Unix.Unix_error "File exists" renameat2
     $TMPDIR/mail/Receipts/cur/one:2,S)
    ("destination collision" (source_preserved true) (destination_preserved true)
     (notmuch_calls (search)))
    (outcome (Folder Unknown))
    ("LLM returned an unknown folder" (name Unknown))
    (outcome (Malformed {}))
    ("invalid mail classification JSON"
     (Of_jsonaf_error
      "lib/classify_mail.ml.Decision.Wire.t_of_jsonaf: the following record elements were undefined: target_folder reason"
      (Object ())))
    (outcome Incomplete)
    ("LLM did not return a complete text answer" (status Incomplete) (error ())
     (incomplete_details ()))
    (outcome Refused)
    ("LLM refused to answer" (refusal No))
    ("after rejected answers" (notmuch_called false))
    ("JSON null" (notmuch_called false) (source_preserved true))
    (V2
     ((time (<time>)) (level (Info))
      (message (Sexp ("classifying mail" (dry_run true) (messages 2))))
      (tags ())))
    (V2
     ((time (<time>)) (level (Info))
      (message
       (Sexp
        ((completed 1) (total 2)
         (classification
          ((subject (invoice)) (message_id (invoice@example.com))
           (target_folder (Receipts)) (reason "Test model classification.")))
         (moved false) (reasoning ()))))
      (tags ())))
    (V2
     ((time (<time>)) (level (Info))
      (message
       (Sexp
        ((completed 2) (total 2)
         (classification
          ((subject (second)) (message_id (second@example.com))
           (target_folder ()) (reason "Test model classification.")))
         (moved false) (reasoning ()))))
      (tags ())))
    ("dry run" (notmuch_called false))
    ("email is too large to classify" (bytes 100142) (max_message_bytes 100000))
    ("invalid UTF-8" (normalized true))
    ((token_calls x) (authorization ("Bearer test-secret")))
    |}];
  return ()
;;

